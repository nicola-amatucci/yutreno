#!/bin/sh
# Downloads the generated code of openETCS (demonstrator release, 2015-2016), compiles it with gcc into a
# static library and builds the minimal test test_evc.
#   sh examples/openetcs/build.sh [working folder]     (default: ./openetcs-build)
# Requires git, gcc and about 600 MB of space. The openETCS code is distributed under the openETCS Open
# License (EUPL 1.1 or later, CC BY-SA 3.0) and stays outside the YuTreno repository.
set -e
HERE=$(cd "$(dirname "$0")" && pwd)
WORK=${1:-openetcs-build}
mkdir -p "$WORK" && cd "$WORK"
[ -d srcAndBinary ] || git clone --depth 1 https://github.com/openETCS/srcAndBinary
SRC=srcAndBinary/GreenDemonstrator/src/OBU/Generated_Code/KCG_GreenField
LIBINC=srcAndBinary/GreenDemonstrator/src/OBU/Generated_Code/KCG-ERSA
mkdir -p obj
echo "Compiling $(ls $SRC/*.c | wc -l) C files generated by SCADE..."
for f in $SRC/*.c; do
  o=obj/$(basename "$f" .c).o
  [ -f "$o" ] || gcc -O1 -w -I"$SRC" -I"$LIBINC" -c "$f" -o "$o"
done
ar rcs libopenetcs_evc.a obj/*.o
gcc -O1 -w -I"$SRC" -I"$LIBINC" "$HERE/test_evc.c" libopenetcs_evc.a -lm -o test_evc
echo "Ready: $(pwd)/libopenetcs_evc.a and $(pwd)/test_evc"
./test_evc
