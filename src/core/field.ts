/**
 * Field: the physical yard as the engine sees it. It generates from the line the control tables of the first layout
 * (the designer's job) and simulates the field elements the interlocking commands and detects through EULYNX:
 *  - points (SCI-P): movement in a given time, detection of the end position, failures (unable to move, no
 *    detection), trailing when a train runs through them from the heel in the wrong position;
 *  - train detection sections, TVPS (SCI-TDS): occupancy by the train and by the train ahead, according to the
 *    branch each one took at the points; failure (disturbed section).
 *
 * The first layout is the simplest one that fits the existing lines: every intermediate station has the main
 * track (I) and a passing track (II) between an entry point and an exit point; the origin station and the
 * terminus have track I only. Stop markers are the signals already generated by the line (home, starting,
 * block), plus a starting marker on track II and one at the end of the line. Chainages on track II are the same
 * as on track I: the branch changes occupancy and limits, not geometry.
 */
import type { CompiledLine } from './types';
import { branch, type ControlTable } from '../trackside/control-table';
import { CPP, OCC, RAMP, RDPP, RPP, TRG, type TracksideConfig, type PointConfig, type SciTelegram, type TvpsConfig } from '../trackside/types';

/** Layout positions of an intermediate station relative to the stop marker (m) */
export const STATION_LAYOUT = { point1: -300, tracksStart: -260, departure: 250, point2: 310, overlapEnd: 350, divergingSpeed: 60, moveTime: 6, overlap: 50 };

/**
 * Generates the control tables of the line: one per station and one for the line block. With `reverse` the tables
 * also have the routes for trains running towards the origin (entries and departures on both tracks, line block,
 * arrival at the origin) and every departure and block route says which single-track segment it enters, for the
 * block consent; without it the tables are those of the nominal direction only.
 */
export function generateLayout(L: CompiledLine, opt: { reverse?: boolean; prefix?: string } = {}): ControlTable[] {
  const P = STATION_LAYOUT, st = L.st, out: ControlTable[] = [], pre = opt.prefix ?? '';
  const markers = L.sig.map(s => ({ ...s }));
  const next = (s: number) => markers.find(m => m.s > s + 1);
  const line: ControlTable = { site: pre + 'Line', station: null, elements: { points: [], track_circuits: [], signals: [] }, routes: [] };
  const lineSeg = (name: string, s: number) => { if (!line.elements.signals.some(x => x.name === name)) line.elements.signals.push({ name: name, chainage_m: s, track: 'I' }); };
  let nBlock = 0;
  /** Block sections and routes from `from` (end of the station overlap) to the home signal of the next station */
  const blockRoutes = (from: number, stop: number) => {
    let a = from, prev: string | null = null;
    const sections: { name: string; a: number; b: number; end: string }[] = [];
    for (const m of markers) {
      if (m.s <= a + 1 || m.s > stop + 1) continue;
      nBlock++;
      const name = 'B' + nBlock, end = m.kind === 'H' ? 'H' + m.id : 'S' + m.id;
      line.elements.track_circuits.push({ name: name, from_m: a, to_m: m.s, track: 'I' });
      sections.push({ name: name, a, b: m.s, end: end });
      lineSeg(end, m.s);
      if (prev) line.routes.push({
        number: name, designation: `Block ${prev} → ${end}`, type: 'block', from: prev, to: end, points: [], track_circuits: [name],
        overlap_path: { length_m: P.overlap, track_circuits: [] }, diverging_speed_kmh: null, conflicting: [], release_mode: 'sectional', automatic: true,
      });
      prev = end; a = m.s;
    }
    return sections;
  };

  for (let k = 0; k < st.length; k++) {
    const S = st[k].s, name = st[k].name;
    const t: ControlTable = { site: pre + name, station: k, elements: { points: [], track_circuits: [], signals: [] }, routes: [] };
    const pSig = markers.find(m => m.kind === 'P' && m.st === k);
    const hSig = k > 0 ? [...markers].reverse().find(m => m.kind === 'H' && m.s < S) : undefined;
    const intermediate = k > 0 && k < st.length - 1 && !!pSig && !!hSig;
    if (k === 0) {
      // origin: track I up to the starting marker
      if (!pSig) { out.push(t); continue; }
      t.elements.signals.push({ name: 'P_I', chainage_m: pSig.s, track: 'I' });
      t.elements.track_circuits.push({ name: 'I', from_m: 0, to_m: pSig.s, track: 'I' });
      const sez = blockRoutes(pSig.s, nextStop(k));
      if (sez.length) {
        t.elements.track_circuits.push(...line.elements.track_circuits.filter(c => c.name === sez[0].name).map(c => ({ ...c, name: '§' + c.name })));
        t.elements.signals.push({ name: sez[0].end, chainage_m: sez[0].b, track: 'I' });
        t.routes.push({
          number: '1', designation: `Departure from ${name} track I`, type: 'departure', from: 'P_I', to: sez[0].end, points: [], track_circuits: ['§' + sez[0].name],
          overlap_path: { length_m: P.overlap, track_circuits: [] }, diverging_speed_kmh: null, conflicting: [], release_mode: 'sectional',
        });
      }
    } else if (intermediate) {
      const h = hSig as NonNullable<typeof hSig>, p = pSig as NonNullable<typeof pSig>;
      const d1 = S + P.point1, d2 = S + P.point2, inTrack = S + P.tracksStart, endO = S + P.overlapEnd;
      t.elements.points.push(
        { number: '1', chainage_m: d1, normal: 'right', reverse_to: 'II', type: 'diverging', move_time_s: P.moveTime },
        { number: '2', chainage_m: d2, normal: 'right', reverse_to: 'II', type: 'converging', move_time_s: P.moveTime },
      );
      t.elements.track_circuits.push(
        { name: '1PZ', from_m: h.s, to_m: inTrack, track: '*' },
        { name: 'I', from_m: inTrack, to_m: p.s, track: 'I' },
        { name: 'II', from_m: inTrack, to_m: p.s, track: 'II' },
        { name: '2PZ', from_m: p.s, to_m: endO, track: '*' },
      );
      t.elements.signals.push(
        { name: 'H' + h.id, chainage_m: h.s, track: 'I' },
        { name: 'P_I', chainage_m: p.s, track: 'I' },
        { name: 'P_II', chainage_m: p.s, track: 'II' },
      );
      const sez = blockRoutes(endO, nextStop(k));
      const endP = sez.length ? sez[0].end : null;
      if (endP) {
        t.elements.track_circuits.push({ name: '§' + sez[0].name, from_m: sez[0].a, to_m: sez[0].b, track: 'I' });
        t.elements.signals.push({ name: endP, chainage_m: sez[0].b, track: 'I' });
      }
      const entry = (n: string, track: 'I' | 'II', dev: string, vel: number | null): ControlTable['routes'][number] => ({
        number: n, designation: `Entry to ${name} on track ${track}`, type: 'entry', from: 'H' + h.id, to: 'P_' + track, points: [dev], track_circuits: ['1PZ', track],
        overlap_path: { length_m: P.overlap, track_circuits: ['2PZ'] }, diverging_speed_kmh: vel, conflicting: [], release_mode: 'sectional',
      });
      const departure = (n: string, track: 'I' | 'II', dev: string, vel: number | null): ControlTable['routes'][number] => ({
        number: n, designation: `Departure from ${name} track ${track}`, type: 'departure', from: 'P_' + track, to: endP as string, points: [dev], track_circuits: ['2PZ', '§' + sez[0].name],
        overlap_path: { length_m: P.overlap, track_circuits: [] }, diverging_speed_kmh: vel, conflicting: [], release_mode: 'sectional',
      });
      t.routes.push(entry('1', 'I', '1N', null), entry('2', 'II', '1R', P.divergingSpeed));
      if (endP) t.routes.push(departure('3', 'I', '2N', null), departure('4', 'II', '2R', P.divergingSpeed));
    } else if (k === st.length - 1 && hSig) {
      // terminus: entry from the home signal to the end-of-line marker
      const end = L.len - 15;
      t.elements.signals.push({ name: 'H' + hSig.id, chainage_m: hSig.s, track: 'I' }, { name: 'END', chainage_m: end, track: 'I' });
      t.elements.track_circuits.push({ name: 'I', from_m: hSig.s, to_m: L.len, track: 'I' });
      t.routes.push({
        number: '1', designation: `Arrival at ${name}`, type: 'arrival', from: 'H' + hSig.id, to: 'END', points: [], track_circuits: ['I'],
        overlap_path: { length_m: 0, track_circuits: [] }, diverging_speed_kmh: null, conflicting: [], release_mode: 'whole_route',
      });
    }
    out.push(t);
  }
  // the first sections after each station belong to the departures: the line does not duplicate them
  const owned = new Set(out.flatMap(t => t.elements.track_circuits.filter(c => c.name.startsWith('§')).map(c => c.name.slice(1))));
  line.elements.track_circuits = line.elements.track_circuits.filter(c => !owned.has(c.name));
  line.routes = line.routes.filter(it => !it.track_circuits.some(c => owned.has(c)));
  out.push(line);
  if (opt.reverse) addReverse(L, out, line);
  return out;

  /** Home signal of the next station (or the end of the line), where the block stops */
  function nextStop(k: number): number { return k + 1 < st.length ? (markers.find(m => m.kind === 'H' && m.s < st[k + 1].s && m.s > st[k].s)?.s ?? st[k + 1].s) : L.len; }
}

/**
 * Routes of the reverse direction, laid over the same elements. Every segment between two stations is single track:
 * its block sections are run from the end towards the origin, the last one (just before the home signal of the next
 * station, in the nominal direction) belongs to the reverse departure of that station. Markers of the reverse
 * direction stand at the section boundaries: on ETCS level 2 they are marker boards, so no lineside signal is needed.
 */
function addReverse(L: CompiledLine, tables: ControlTable[], line: ControlTable): void {
  const P = STATION_LAYOUT, n = L.st.length;
  const stations = tables.filter(t => t.station != null).sort((a, b) => (a.station as number) - (b.station as number));
  const sig = (t: ControlTable, nm: string) => t.elements.signals.find(x => x.name === nm);
  const home = (t: ControlTable) => t.elements.signals.find(x => /^H/.test(x.name));
  // start of the line beyond each station in the nominal direction (where its departures end their points zone)
  const startOf = (k: number): number | null => {
    const t = stations[k];
    if (k === 0) return sig(t, 'P_I')?.chainage_m ?? null;
    return t.elements.points.length ? L.st[k].s + P.overlapEnd : null;
  };
  const sections = tables.flatMap(t => t.elements.track_circuits.filter(c => /^§?B\d+$/.test(c.name)).map(c => ({ id: t.site + '/' + c.name, name: c.name.replace('§', ''), a: c.from_m, b: c.to_m, site: t.site })))
    .sort((x, y) => x.a - y.a);
  const route = (t: ControlTable, r: Omit<ControlTable['routes'][number], 'number' | 'conflicting' | 'direction'>) =>
    t.routes.push({ number: String(t.routes.length + 1), conflicting: [], direction: 'reverse', ...r });
  // the nominal departures and block routes enter a segment too
  for (const t of stations) for (const r of t.routes) if (r.type === 'departure') r.line_segment = t.station as number;
  for (let k = 0; k + 1 < n; k++) {
    const a0 = startOf(k), next = stations[k + 1], h = home(next);
    if (a0 == null || !h) continue;
    const seg = sections.filter(c => c.a >= a0 - 1 && c.b <= h.chainage_m + 1);
    if (!seg.length) continue;
    for (const r of line.routes) if (seg.some(c => r.track_circuits.includes(c.name))) r.line_segment = k;
    const here = stations[k];
    // markers: the reverse home of station k at the start of the segment, one at the start of every other section
    here.elements.signals.push({ name: 'RH', chainage_m: a0, track: 'I', direction: 'reverse' });
    const mk = (i: number) => (i === 0 ? here.site + '/RH' : line.site + '/R' + seg[i].name);
    for (let i = 1; i < seg.length; i++) line.elements.signals.push({ name: 'R' + seg[i].name, chainage_m: seg[i].a, track: 'I', direction: 'reverse' });
    // line block, from the end of the segment towards station k (the last section belongs to the departure of k + 1)
    for (let i = seg.length - 2; i >= 0; i--) {
      line.routes.push({
        number: 'R' + seg[i].name, designation: `Block ${mk(i + 1).split('/')[1]} → ${mk(i).split('/')[1]} (reverse)`, type: 'block', from: mk(i + 1), to: mk(i), points: [],
        track_circuits: [seg[i].id], overlap_path: { length_m: P.overlap, track_circuits: [] }, diverging_speed_kmh: null, conflicting: [], release_mode: 'sectional',
        automatic: true, direction: 'reverse', line_segment: k,
      });
    }
    // departures of station k + 1 towards k
    const last = seg[seg.length - 1], to = mk(seg.length - 1), nm = next.site;
    if (k + 1 === n - 1) {
      next.elements.signals.push({ name: 'RP_I', chainage_m: h.chainage_m, track: 'I', direction: 'reverse' });
      route(next, { designation: `Departure from ${nm} track I (reverse)`, type: 'departure', from: 'RP_I', to, points: [], track_circuits: [last.id],
        overlap_path: { length_m: P.overlap, track_circuits: [] }, diverging_speed_kmh: null, release_mode: 'sectional', line_segment: k });
    } else if (next.elements.points.length) {
      const inTrack = L.st[k + 1].s + P.tracksStart;
      next.elements.signals.push({ name: 'RP_I', chainage_m: inTrack, track: 'I', direction: 'reverse' }, { name: 'RP_II', chainage_m: inTrack, track: 'II', direction: 'reverse' });
      for (const [track, pt, v] of [['I', '1N', null], ['II', '1R', P.divergingSpeed]] as const) {
        route(next, { designation: `Departure from ${nm} track ${track} (reverse)`, type: 'departure', from: 'RP_' + track, to, points: [pt], track_circuits: ['1PZ', last.id],
          overlap_path: { length_m: P.overlap, track_circuits: [] }, diverging_speed_kmh: v, release_mode: 'sectional', line_segment: k });
      }
    }
  }
  // entries of the intermediate stations from the far side, and the arrival at the origin
  for (let k = 1; k + 1 < n; k++) {
    const t = stations[k];
    if (!t.elements.points.length || !sig(t, 'RH') || !sig(t, 'RP_I')) continue;
    for (const [track, pt, v] of [['I', '2N', null], ['II', '2R', P.divergingSpeed]] as const) {
      route(t, { designation: `Entry to ${t.site} on track ${track} (reverse)`, type: 'entry', from: 'RH', to: 'RP_' + track, points: [pt], track_circuits: ['2PZ', track],
        overlap_path: { length_m: P.overlap, track_circuits: ['1PZ'] }, diverging_speed_kmh: v, release_mode: 'sectional' });
    }
  }
  const o = stations[0];
  if (sig(o, 'RH') && o.elements.track_circuits.some(c => c.name === 'I')) {
    o.elements.signals.push({ name: 'REND', chainage_m: 15, track: 'I', direction: 'reverse' });
    route(o, { designation: `Arrival at ${o.site} (reverse)`, type: 'arrival', from: 'RH', to: 'REND', points: [], track_circuits: ['I'],
      overlap_path: { length_m: 0, track_circuits: [] }, diverging_speed_kmh: null, release_mode: 'whole_route' });
  }
}

/** A movement through a node of a network: from line `from` to line `to`, with the direction on each */
export interface NodeMove { node: string; from: string; fromDir: 1 | -1; to: string; toDir: 1 | -1 }

/** Layout of a line of a network: its control tables, with the prefix of its sites (none for the main line) */
export interface LineLayout { id: string; L: CompiledLine; tables: ControlTable[] }

/**
 * Node routes of a network (step 4b, docs/design/network.md). A node joins line A, where its station is intermediate
 * (tracks I and II between points 1 and 2), and line B, which starts or ends there. On A the station gets two junction
 * points at the stop marker, J1 on track I and J2 on track II, which in reverse lead to B: the routes of A over track I
 * lock J1 normal, those over track II lock J2 normal. For every movement used by the trains:
 *  - from A to B: a route of A from the home signal to the node marker N_I/N_II on track I or II with J1 or J2
 *    reverse (out), and a route of B from the node to its first marker (in);
 *  - from B to A: a route of B from its last marker to the node (out), and a route of A from the node marker on
 *    track I or II to the starting marker of that track (in).
 * The station of the node belongs to A; the interlocking of B ends at the node. Routes out need the boundary consent of
 * the node, which one interlocking holds at a time; it is exchanged as the block consent of a single-track segment,
 * and on B it goes with the consent of the segment next to the node.
 * Returns the boundaries, with the id of the consent and the interlocking holding it at the start: A when B starts
 * at the node, B when it ends there (the side the single-track segment of B next to the node is open to at the start).
 */
export function addNodeRoutes(layouts: LineLayout[], moves: NodeMove[]): { id: string; node: string; a: string; b: string; holder: string }[] {
  const P = STATION_LAYOUT, out: { id: string; node: string; a: string; b: string; holder: string }[] = [];
  const byId = new Map(layouts.map(l => [l.id, l]));
  const kind = (l: LineLayout, name: string) => {
    const k = l.L.st.findIndex(x => x.name === name);
    if (k < 0) throw new Error(`node ${name}: not a station of line ${l.id}`);
    const t = l.tables.find(x => x.station === k) as ControlTable;
    return { k, t, S: l.L.st[k].s, terminal: k === 0 ? 'origin' as const : k === l.L.st.length - 1 ? 'terminus' as const : null, twoTracks: t.elements.points.some(p => p.number === '1') };
  };
  const seen = new Set<string>();
  for (const m of moves) {
    const x = byId.get(m.from) as LineLayout, y = byId.get(m.to) as LineLayout, kx = kind(x, m.node), ky = kind(y, m.node);
    // A is the line where the node has two tracks, B the one that starts or ends there
    let A: LineLayout, B: LineLayout, kA: ReturnType<typeof kind>, kB: ReturnType<typeof kind>, toB: boolean, dA: 1 | -1;
    if (kx.twoTracks && ky.terminal) { A = x; B = y; kA = kx; kB = ky; toB = true; dA = m.fromDir; }
    else if (ky.twoTracks && kx.terminal) { A = y; B = x; kA = ky; kB = kx; toB = false; dA = m.toDir; }
    else throw new Error(`node ${m.node}: the interlocking trackside needs the node to be a station with two tracks on one line (${kx.twoTracks ? x.id : y.id}) and the end of the other`);
    const id = `${m.node}|${A.id}|${B.id}`;
    // at the start the consent is with the side the single-track segment of B next to the node is open to: the origin
    // side holds the block consents, so A when B starts at the node and B when it ends there
    if (!out.some(b => b.id === id)) out.push({ id, node: m.node, a: A.id, b: B.id, holder: kB.terminal === 'origin' ? A.id : B.id });
    const key = `${id}|${toB}|${dA}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const tA = kA.t, tB = kB.t, S = kA.S, SB = kB.S;
    if (!tA.elements.points.some(p => p.number === 'J1')) {
      tA.elements.points.push(
        { number: 'J1', chainage_m: S, normal: 'right', reverse_to: 'I', type: 'junction', move_time_s: P.moveTime, junction: B.id },
        { number: 'J2', chainage_m: S, normal: 'right', reverse_to: 'II', type: 'junction', move_time_s: P.moveTime, junction: B.id },
      );
      // the routes over the tracks of the station keep the junctions straight
      for (const r of tA.routes) {
        if (r.track_circuits.includes('I')) r.points.push('J1N');
        if (r.track_circuits.includes('II')) r.points.push('J2N');
      }
    }
    const mark = (t: ControlTable, name: string, s_m: number, track: string, dir: 1 | -1) => {
      if (!t.elements.signals.some(z => z.name === name)) t.elements.signals.push({ name, chainage_m: s_m, track, ...(dir < 0 ? { direction: 'reverse' as const } : {}), node: id });
    };
    const sig = (t: ControlTable, name: string) => {
      const z = t.elements.signals.find(q => q.name === name);
      if (!z) throw new Error(`node ${m.node}: signal ${name} missing at ${t.site} (line ${t === tA ? A.id : B.id})`);
      return name;
    };
    const home = (t: ControlTable) => (t.elements.signals.find(q => /^H/.test(q.name)) as { name: string }).name;
    const push = (t: ControlTable, r: Omit<ControlTable['routes'][number], 'number' | 'conflicting'>) => t.routes.push({ number: 'N' + (t.routes.length + 1), conflicting: [], ...r });
    const linkTo = (line: string, side: 'out' | 'in') => ({ line, side, boundary: id });
    const rev = (d: 1 | -1) => (d < 0 ? { direction: 'reverse' as const } : {});
    const nameA = A.L.st[kA.k].name, nB = B.id, nA = A.id;
    for (const track of ['I', 'II'] as const) {
      const j = track === 'I' ? 'J1' : 'J2', v = track === 'II' ? P.divergingSpeed : null;
      if (toB) {
        // from A into the node and on to B
        const nm = (dA > 0 ? 'N_' : 'RN_') + track;
        mark(tA, nm, S, track, dA);
        if (dA > 0) push(tA, { designation: `Entry to ${nameA} on track ${track} towards ${nB}`, type: 'entry', from: home(tA), to: nm, points: [track === 'I' ? '1N' : '1R', j + 'R'],
          track_circuits: ['1PZ', track], overlap_path: { length_m: 0, track_circuits: [] }, diverging_speed_kmh: v, release_mode: 'sectional', link: linkTo(nB, 'out') });
        else push(tA, { designation: `Entry to ${nameA} on track ${track} towards ${nB} (reverse)`, type: 'entry', from: sig(tA, 'RH'), to: nm, points: [track === 'I' ? '2N' : '2R', j + 'R'],
          track_circuits: ['2PZ', track], overlap_path: { length_m: 0, track_circuits: [] }, diverging_speed_kmh: v, release_mode: 'sectional', link: linkTo(nB, 'out'), ...rev(-1) });
      } else {
        // from B through the node onto a track of A, up to the starting marker of that track
        const nm = (dA > 0 ? 'N_' : 'RN_') + track;
        mark(tA, nm, S, track, dA);
        if (dA > 0) push(tA, { designation: `Entry from ${nB} to ${nameA} on track ${track}`, type: 'entry', from: nm, to: sig(tA, 'P_' + track), points: [j + 'R'],
          track_circuits: [track], overlap_path: { length_m: P.overlap, track_circuits: ['2PZ'] }, diverging_speed_kmh: v, release_mode: 'sectional', link: linkTo(nB, 'in') });
        else push(tA, { designation: `Entry from ${nB} to ${nameA} on track ${track} (reverse)`, type: 'entry', from: nm, to: sig(tA, 'RP_' + track), points: [j + 'R'],
          track_circuits: [track], overlap_path: { length_m: P.overlap, track_circuits: ['1PZ'] }, diverging_speed_kmh: v, release_mode: 'sectional', link: linkTo(nB, 'in'), ...rev(-1) });
      }
    }
    // the side of B: its end at the node
    const dB: 1 | -1 = kB.terminal === 'origin' ? (toB ? 1 : -1) : (toB ? -1 : 1);
    const nm = dB > 0 ? 'N' : 'RN';
    mark(tB, nm, SB, 'I', dB);
    const station = B.L.st[kB.k].name;
    if (toB) {
      // in: from the node to the first marker of B in the direction of running
      const to = kB.terminal === 'origin' ? sig(tB, 'P_I') : sig(tB, 'RP_I');
      push(tB, { designation: `Entry from ${nA} at ${station}${dB < 0 ? ' (reverse)' : ''}`, type: 'entry', from: nm, to, points: [], track_circuits: ['I'],
        overlap_path: { length_m: P.overlap, track_circuits: [] }, diverging_speed_kmh: null, release_mode: 'sectional', link: linkTo(nA, 'in'), ...rev(dB) });
    } else {
      // out: from the last marker of B to the node
      const from = kB.terminal === 'origin' ? sig(tB, 'RH') : home(tB);
      push(tB, { designation: `Entry to ${station} towards ${nA}${dB < 0 ? ' (reverse)' : ''}`, type: 'entry', from, to: nm, points: [], track_circuits: ['I'],
        overlap_path: { length_m: 0, track_circuits: [] }, diverging_speed_kmh: null, release_mode: 'sectional', link: linkTo(nA, 'out'), ...rev(dB) });
    }
  }
  return out;
}

/** Complete trackside configuration, from the translation of the control tables */
export function tracksideConfig(L: CompiledLine, tr: { tvps: TvpsConfig[]; points: PointConfig[]; markers: TracksideConfig['markers']; routes: TracksideConfig['routes'] }, balises: { NID_BG: number; s: number }[], baseLim: [number, number, number][]): TracksideConfig {
  return {
    line: { name: L.def.name, length_m: L.len, limits: baseLim.map(l => [l[0], Math.min(l[1], L.len + 1000), l[2]] as [number, number, number]), gradients: L.prof.map(p => [p.a, p.b, p.i] as [number, number, number]) },
    balises: balises.map(b => ({ NID_BG: b.NID_BG, s_m: b.s })),
    tvps: tr.tvps, points: tr.points, markers: tr.markers, routes: tr.routes,
    timetable: L.st.map((s, i) => ({ station: i, name: s.name, arrival_s: s.arr, departure_s: s.dep, s_m: s.s })),
    parameters: { ars: true, cancel_delay_s: 120, ma_renewal_s: 5, release_kmh: 15, return_to_normal: true },
  };
}

// ---------------------------------------------------------------------------------------------
// Simulation of the field elements

interface PointState {
  cfg: PointConfig;
  pos: 'N' | 'R';
  /** Commanded position and time the movement ends; null when at rest */
  target: 'N' | 'R' | null;
  until: number;
  fault: 'none' | 'blocked' | 'no_detection';
  trailed: boolean;
  lastReport: string;
}
interface TvpsState { cfg: TvpsConfig; occ: boolean; disturbed: boolean; lastReport: string }
/** A train on the field: head in line chainages, direction of running (+1 towards the end of the line, −1 towards the origin) */
interface TrainOnField { head: number; len: number; branches: Set<string>; prevHead: number; dir: 1 | -1; wasOn: boolean }

/** Station loop: entry point, exit point and branch of track II */
interface Loop { branch: string; a: number; b: number; d1: string; d2: string; vDev: number }

export class Field {
  readonly points = new Map<string, PointState>();
  readonly tvps = new Map<string, TvpsState>();
  readonly loops: Loop[] = [];
  /** Controlled train and train ahead */
  readonly trains: TrainOnField[] = [];
  private outbox: SciTelegram[] = [];
  /** Events to log (trailed points, failures) */
  readonly events: string[] = [];

  constructor(readonly cfg: TracksideConfig) {
    for (const d of cfg.points) this.points.set(d.id, { cfg: d, pos: 'N', target: null, until: 0, fault: 'none', trailed: false, lastReport: '' });
    for (const t of cfg.tvps) this.tvps.set(t.id, { cfg: t, occ: false, disturbed: false, lastReport: '' });
    const byBranch = new Map<string, PointConfig[]>();
    for (const d of cfg.points) { const l = byBranch.get(d.reverse_branch) || []; l.push(d); byBranch.set(d.reverse_branch, l); }
    for (const [r, ds] of byBranch) {
      const d1 = ds.find(d => d.type === 'diverging'), d2 = ds.find(d => d.type === 'converging');
      if (!d1 || !d2) continue;
      const vDev = Math.min(...cfg.routes.filter(it => it.points.some(x => x.id === d1.id && x.position === 'R')).flatMap(it => it.speeds.map(v => v[2])), 1e9);
      this.loops.push({ branch: r, a: d1.s_m, b: d2.s_m, d1: d1.id, d2: d2.id, vDev: isFinite(vDev) ? vDev : 1e9 });
    }
  }

  /** Adds a train to the field (head and length); returns its index */
  addTrain(head: number, len: number, dir: 1 | -1 = 1): number { this.trains.push({ head, len, branches: new Set(), prevHead: head, dir, wasOn: false }); return this.trains.length - 1; }

  /** Direction of a train on this line, after a reroute of a train not yet on the field */
  setDirection(i: number, dir: 1 | -1): void { const tr = this.trains[i]; if (tr && !tr.wasOn) tr.dir = dir; }

  /** Passing-track branches a part of the train is on */
  branchesOf(i: number): Set<string> { return this.trains[i].branches; }

  /** Speed limit of the branch under the train (km/h), Infinity if the whole train is on the main track */
  branchLimit(i: number, head: number): number {
    const tr = this.trains[i];
    let v = Infinity;
    const [a, b] = tr.dir > 0 ? [head - tr.len, head] : [head, head + tr.len];
    for (const lp of this.loops) if (tr.branches.has(lp.branch) && a < lp.b + 10 && b > lp.a - 10) v = Math.min(v, lp.vDev);
    return v;
  }

  /** Commands from the interlocking (SCI-P) */
  receive(tgs: SciTelegram[], t: number): void {
    for (const g of tgs) {
      if (g.interface !== 'SCI-P' || g.message !== 'Cd_Move_Point') continue;
      const p = this.points.get(g.receiver);
      if (!p) continue;
      const wanted: 'N' | 'R' = (g.Commanded_Point_Position === CPP.right) === (p.cfg.normal === 'right') ? 'N' : 'R';
      if (p.fault === 'blocked' || p.trailed) {
        this.outbox.push({ interface: 'SCI-P', message: 'Msg_Movement_Failed', sender: p.cfg.id, receiver: 'IXL' });
        continue;
      }
      if (p.target == null && p.pos === wanted) { p.lastReport = ''; continue; }
      p.target = wanted; p.until = t + p.cfg.move_time_s;
    }
  }

  /** Element failures, from the scenarios; element names of version 0.x (`Linea/…`) are accepted */
  pointFault(id: string, mode: 'blocked' | 'no_detection' | 'none'): boolean {
    const p = this.points.get(legacyId(id)); if (!p) return false;
    p.fault = mode; p.lastReport = '';
    return true;
  }
  tvpsFault(id: string, on: boolean): boolean {
    const s = this.tvps.get(legacyId(id)); if (!s) return false;
    s.disturbed = on; s.lastReport = '';
    return true;
  }

  /** Advances the field: point movements, branches taken by the trains, occupancy */
  step(t: number, heads: { head: number; len: number; on: boolean }[]): void {
    for (const p of this.points.values()) {
      if (p.target != null && t + 1e-9 >= p.until) {
        // with no detection the point machine moves, but the end position is never detected
        p.pos = p.target; p.target = null;
      }
    }
    heads.forEach((h, i) => {
      const tr = this.trains[i];
      if (!tr) return;
      tr.prevHead = tr.head; tr.head = h.head; tr.len = h.len;
      const entering = h.on && !tr.wasOn;
      tr.wasOn = h.on;
      if (!h.on) { tr.branches.clear(); return; }
      if (entering) this.enterAtJunction(tr);
      for (const lp of this.loops) {
        // the first point met in the direction of running is taken from the toe, the second from the heel
        const fwd = tr.dir > 0;
        const toe = this.points.get(fwd ? lp.d1 : lp.d2) as PointState, heel = this.points.get(fwd ? lp.d2 : lp.d1) as PointState;
        const xToe = fwd ? lp.a : lp.b, xHeel = fwd ? lp.b : lp.a;
        const passes = (x: number) => (fwd ? tr.prevHead < x && tr.head >= x : tr.prevHead > x && tr.head <= x);
        // the head passes the toe: it takes the branch given by the point position
        if (passes(xToe)) {
          if (toe.target != null) this.trail(toe, 'run over while moving');
          if (toe.pos === 'R') tr.branches.add(lp.branch); else tr.branches.delete(lp.branch);
        }
        // the head reaches the other point from the heel: it must be set for the branch the train comes from
        if (passes(xHeel)) {
          const need: 'N' | 'R' = tr.branches.has(lp.branch) ? 'R' : 'N';
          if (heel.target != null || heel.pos !== need) this.trail(heel, 'run through from the heel in ' + (heel.pos === 'N' ? 'normal' : 'reverse') + ' position');
        }
        if (fwd ? tr.head - tr.len > lp.b + 1 : tr.head + tr.len < lp.a - 1) tr.branches.delete(lp.branch);
      }
    });
    for (const s of this.tvps.values()) {
      let occ = false;
      heads.forEach((h, i) => { if (h.on && this.trains[i] && this.occupies(this.trains[i], s.cfg)) occ = true; });
      s.occ = occ;
    }
  }

  /**
   * A train that comes onto this line at a node (network): its rear is at the junction points, and it is on the track
   * the reversed junction leads to. With no junction reversed there it runs through them the wrong way
   */
  private enterAtJunction(tr: TrainOnField): void {
    const rear = tr.dir > 0 ? tr.head - tr.len : tr.head + tr.len;
    const js = [...this.points.values()].filter(p => p.cfg.type === 'junction' && Math.abs(p.cfg.s_m - rear) < 30);
    if (!js.length) return;
    const rev = js.find(p => p.pos === 'R' && p.target == null);
    if (!rev) { this.trail(js[0], 'run through from the junction of the node with no junction reversed'); return; }
    if (rev.cfg.reverse_branch !== 'I') tr.branches.add(rev.cfg.reverse_branch);
  }

  private trail(p: PointState, why: string): void {
    if (p.trailed) return;
    p.trailed = true; p.target = null; p.lastReport = '';
    this.events.push(`Point ${p.cfg.id} trailed: ${why}`);
  }

  /** Does the train occupy the section? Takes into account the branch taken between the points */
  private occupies(tr: TrainOnField, s: TvpsConfig): boolean {
    const lo = tr.dir > 0 ? tr.head - tr.len : tr.head, hi = tr.dir > 0 ? tr.head : tr.head + tr.len;
    const a = Math.max(lo, s.from_m), b = Math.min(hi, s.to_m);
    if (b <= a) return false;
    if (s.branch === '*') return true;
    // part of the train body on each branch
    for (const lp of this.loops) {
      if (b <= lp.a || a >= lp.b) continue;
      const onLoop = tr.branches.has(lp.branch);
      if (s.branch === lp.branch) return onLoop;
      if (s.branch === 'I' && onLoop && a >= lp.a && b <= lp.b) return false;
    }
    return s.branch === 'I';
  }

  /** Indexes of the trains on the field that occupy a section (for the checks: never more than one) */
  occupiedBy(id: string): number[] {
    const s = this.tvps.get(id);
    if (!s) return [];
    return this.trains.flatMap((tr, i) => (tr.wasOn && this.occupies(tr, s.cfg) ? [i] : []));
  }

  /** Telegrams to the interlocking: everything at the start, then only changes */
  telegrams(): SciTelegram[] {
    const out = this.outbox.splice(0);
    for (const p of this.points.values()) {
      const rpp = p.trailed ? RPP.unintended : p.target != null || p.fault === 'no_detection' ? RPP.none : (p.pos === 'N') === (p.cfg.normal === 'right') ? RPP.right : RPP.left;
      const ability = p.fault === 'blocked' || p.trailed ? RAMP.unable_to_move : RAMP.able_to_move;
      const key = rpp + ':' + ability;
      if (key === p.lastReport) continue;
      const first = p.lastReport === '';
      p.lastReport = key;
      out.push({ interface: 'SCI-P', message: 'Msg_Point_Position', sender: p.cfg.id, receiver: 'IXL', Reported_Point_Position: rpp, Reported_Degraded_Point_Position: RDPP.not_applicable });
      if (first || ability === RAMP.unable_to_move) out.push({ interface: 'SCI-P', message: 'Msg_Ability_To_Move_Point', sender: p.cfg.id, receiver: 'IXL', Reported_Ability_To_Move_Point_Status: ability });
    }
    for (const s of this.tvps.values()) {
      const occ = s.disturbed ? OCC.disturbed : s.occ ? OCC.occupied : OCC.vacant;
      const key = String(occ);
      if (key === s.lastReport) continue;
      const trig = s.lastReport === '' ? TRG.initial : s.disturbed ? TRG.failure : TRG.passage;
      s.lastReport = key;
      out.push({
        interface: 'SCI-TDS', message: 'Msg_TVPS_Occupancy_Status', sender: s.cfg.id, receiver: 'IXL', Occupancy_Status: occ,
        Ability_To_Be_Forced_To_Clear: 0x01, Filling_Level: null, POM_Status: 0xff, Disturbance_Status: s.disturbed ? 0x02 : 0xff, Change_Trigger: trig,
      });
    }
    return out;
  }
}

